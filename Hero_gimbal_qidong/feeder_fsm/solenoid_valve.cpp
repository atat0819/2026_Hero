/**
 * @file   solenoid_valve.cpp
 * @brief  电磁阀驱动 — 通过 GPIO 高低电平控制电磁阀开/关
 *
 * 电平约定: 高电平 = 开阀, 低电平 = 关阀
 * 时序管理: 纯电平控制, 开/关持续时间由调用方 (FSM/任务) 负责
 */

#include "solenoid_valve.hpp"

// ============================================================================
// 构造: 绑定 GPIO 端口与引脚
// ============================================================================
Class_Solenoid_Valve::Class_Solenoid_Valve(GPIO_TypeDef *port, uint16_t pin)
    : port_(port), pin_(pin), is_open_(false)
{
}

// ============================================================================
// 初始化: 上电安全, 强制关阀
// ============================================================================
void Class_Solenoid_Valve::Init()
{
    Close();
}

// ============================================================================
// 开阀: 引脚置高
// ============================================================================
void Class_Solenoid_Valve::Open()
{
    HAL_GPIO_WritePin(port_, pin_, GPIO_PIN_SET);
    is_open_ = true;
}

// ============================================================================
// 关阀: 引脚置低
// ============================================================================
void Class_Solenoid_Valve::Close()
{
    HAL_GPIO_WritePin(port_, pin_, GPIO_PIN_RESET);
    is_open_ = false;
}

// ============================================================================
// 查询当前状态
// ============================================================================
bool Class_Solenoid_Valve::Is_Open() const
{
    return is_open_;
}

