// 全局实例: 两路电磁阀
// ============================================================================
Class_Solenoid_Valve solenoid_valve_1(GPIOI, GPIO_PIN_0);  // PI0
Class_Solenoid_Valve solenoid_valve_2(GPIOH, GPIO_PIN_12); // PH12
