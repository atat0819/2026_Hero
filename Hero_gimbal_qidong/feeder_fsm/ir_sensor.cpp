/**
 * @file   ir_sensor.cpp
 * @brief  红外对射传感器驱动 — 检测弹丸是否进入进弹口
 *
 * 电平约定: 有弹(遮挡光路) = 高电平, 无弹 = 低电平
 * 防抖: 连续 IR_DEBOUNCE_TICKS 次采样一致才翻转 has_ball_,
 *       避免弹丸在进弹口抖动导致推杆误动作
 */

#include "ir_sensor.hpp"

// ============================================================================
// 初始化: 清零防抖状态 (引脚已在 CubeMX 配置: PH11 输入 + 下拉)
// ============================================================================
void Class_IR_Sensor::Init()
{
    stable_count_ = 0U;
    has_ball_     = false;
    raw_level_    = false;
}

// ============================================================================
// 周期采样 + 软件防抖 (每 5ms 由任务层调用)
// ============================================================================
void Class_IR_Sensor::Update()
{
    raw_level_ = (HAL_GPIO_ReadPin(GPIOH, GPIO_PIN_11) == GPIO_PIN_SET);  // PH11 (CubeMX 配置)

    if (raw_level_ == has_ball_)
    {
        stable_count_ = 0U;   // 与当前稳定状态一致, 复位计数
    }
    else if (++stable_count_ >= IR_DEBOUNCE_TICKS)
    {
        has_ball_     = raw_level_;  // 连续 N 次一致, 确认翻转
        stable_count_ = 0U;
    }
}

// ============================================================================
// 防抖后: 进弹口是否有弹
// ============================================================================
bool Class_IR_Sensor::Has_Ball() const
{
    return has_ball_;
}

// ============================================================================
// 防抖前原始电平 (诊断用)
// ============================================================================
bool Class_IR_Sensor::Get_Raw_Level() const
{
    return raw_level_;
}

